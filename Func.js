let currentLang = 'ta';
try { currentLang = localStorage.getItem('lang') || 'ta'; } catch (e) {}

function applyLanguage(lang) {

  // Translate text
  const els = document.querySelectorAll('[data-i18n]');

  els.forEach(el => {
    const key = el.dataset.i18n;

    if (i18n[lang] && i18n[lang][key]) {
      if (el.tagName === 'TITLE') {
        el.textContent = i18n[lang][key];
      } else {
        el.innerHTML = i18n[lang][key];
      }
    }
  });

  // Change image
  const heroImage = document.getElementById("heroImage");

  // Update button text
  document.querySelectorAll('.lang-btn').forEach(function (btn) {
    btn.textContent = lang === 'ta' ?  'தமிழ்' : 'English';
  });

  // Save language and set class for CSS targeting
  document.documentElement.lang = lang;
  document.documentElement.classList.remove('lang-ta', 'lang-en');
  document.documentElement.classList.add('lang-' + lang);
  try { localStorage.setItem('lang', lang); } catch (e) {}
  currentLang = lang;

}


document.addEventListener('DOMContentLoaded', function () {
  window.scrollTo(0, 0);
  applyLanguage(currentLang);
  document.querySelectorAll('.lang-btn').forEach(function (btn) {
    btn.addEventListener('click', function (e) {
      e.preventDefault();
      applyLanguage(currentLang === 'ta' ? 'en' : 'ta');
    });
  });
});
